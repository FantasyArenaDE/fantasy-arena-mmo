export function releaseWarriorAudioUrl(original: string): string {
  if (/^\/audio\/sfx\/impact_masterwork_execution\.mp3(?:\?v=[a-f0-9]{12})?$/.test(original)) {
    return '/audio/fantasy-arena/warrior/impact_masterwork_execution.wav';
  }
  const match = original.match(/^\/audio\/sfx\/([a-z_]+)_([12])\.mp3(?:\?v=[a-f0-9]{12})?$/);
  if (!match || !CUES.has(match[1])) return original;
  return `/audio/fantasy-arena/warrior/${match[1]}_${match[2]}.wav`;
}
